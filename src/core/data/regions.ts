/** Travel time in seconds between two regions (used for cargo). */
export function travelSeconds(a: RegionId, b: RegionId): number {
  if (a === b) return 20;
  const [ax, ay] = REGION[a].mapPos;
  const [bx, by] = REGION[b].mapPos;
  return Math.round(30 + 110 * Math.hypot(ax - bx, ay - by));
}
